-- Bronze extension for the final pipeline; preserves existing historical data.
USE ROLE SYSADMIN;
USE WAREHOUSE SIDEFLIX_WH;
USE DATABASE SIDEFLIX;
USE SCHEMA BRONZE;
CREATE TABLE IF NOT EXISTS SIDEFLIX.LAB.CATALOG_REFERENCE AS SELECT * FROM SIDEFLIX.BRONZE.CATALOG;
CREATE TABLE IF NOT EXISTS SIDEFLIX.LAB.SESSIONS_REFERENCE AS SELECT * FROM SIDEFLIX.BRONZE.SESSIONS_RAW;
-- Existing historical Gold reference tables are preserved, but are not required
-- or recreated here: Gold does not exist yet on a clean installation.
CREATE TABLE IF NOT EXISTS SIDEFLIX.LAB.DAILY_USAGE (
 USAGE_DATE DATE, VALID_SESSIONS NUMBER, MINUTES_WATCHED NUMBER(18,6),
 PUBLISHED_AT TIMESTAMP_TZ, RUN_ID VARCHAR, VALIDATION_ID VARCHAR, ATTEMPT NUMBER);
CREATE TABLE IF NOT EXISTS SIDEFLIX.LAB.DBT_RESULTS (
 INVOCATION_ID VARCHAR, RUN_AT TIMESTAMP_TZ, COMMAND VARCHAR, RUNTIME VARCHAR,
 NODE VARCHAR, RESOURCE_TYPE VARCHAR, STATUS VARCHAR,
 FAILURES NUMBER, EXECUTION_SECONDS NUMBER(10,2));
ALTER TABLE CATALOG ADD COLUMN IF NOT EXISTS IMDB_TCONST VARCHAR;
ALTER TABLE CATALOG ADD COLUMN IF NOT EXISTS SOURCE_SYSTEM VARCHAR;
ALTER TABLE CATALOG ADD COLUMN IF NOT EXISTS _SOURCE_FILE VARCHAR;
ALTER TABLE CATALOG ADD COLUMN IF NOT EXISTS _BATCH_ID VARCHAR;
ALTER TABLE SESSIONS_RAW ADD COLUMN IF NOT EXISTS SOURCE_SYSTEM VARCHAR;
ALTER TABLE SESSIONS_RAW ADD COLUMN IF NOT EXISTS _BATCH_ID VARCHAR;
CREATE TABLE IF NOT EXISTS IMDB_RAW (
 RAW VARIANT, _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
 _BATCH_ID VARCHAR, SOURCE_SYSTEM VARCHAR);
CREATE TABLE IF NOT EXISTS MOVIELENS_RAW LIKE IMDB_RAW;
CREATE TABLE IF NOT EXISTS NETFLIX_RAW LIKE IMDB_RAW;
CREATE TABLE IF NOT EXISTS WIKIDATA_RAW LIKE IMDB_RAW;
CREATE TABLE IF NOT EXISTS WIKIMEDIA_RAW LIKE IMDB_RAW;
CREATE TABLE IF NOT EXISTS PUBLIC_SOURCE_RUNS (
 RUN_ID VARCHAR, SOURCE_SYSTEM VARCHAR, BATCH_ID VARCHAR,
 STARTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), ROWS_LOADED NUMBER, STATUS VARCHAR);
CREATE STAGE IF NOT EXISTS PUBLIC_SOURCES_STAGE;
CREATE FILE FORMAT IF NOT EXISTS PUBLIC_CSV TYPE=CSV FIELD_DELIMITER=',' SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"';
CREATE FILE FORMAT IF NOT EXISTS PUBLIC_TSV TYPE=CSV FIELD_DELIMITER='\t' SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"';
SELECT TABLE_NAME, ROW_COUNT FROM SIDEFLIX.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA='BRONZE' AND TABLE_NAME IN
('IMDB_RAW','MOVIELENS_RAW','NETFLIX_RAW','WIKIDATA_RAW','WIKIMEDIA_RAW') ORDER BY TABLE_NAME;
