-- Chosen prototype budget: 10 credits/month; warning at 5 and 8, suspend at 10.
-- Configure administrator e-mail notifications in Snowsight; SHOW proves visibility.
-- IF NOT EXISTS preserves any monitor already created: inspect the output/settings.
CREATE RESOURCE MONITOR IF NOT EXISTS SIDEFLIX_MONTHLY
 WITH CREDIT_QUOTA=10 FREQUENCY=MONTHLY START_TIMESTAMP=IMMEDIATELY
 TRIGGERS ON 50 PERCENT DO NOTIFY ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE SIDEFLIX_WH SET RESOURCE_MONITOR=SIDEFLIX_MONTHLY;
SHOW RESOURCE MONITORS LIKE 'SIDEFLIX_MONTHLY';
SHOW WAREHOUSES LIKE 'SIDEFLIX_WH';
SHOW GRANTS TO ROLE SIDEFLIX_ANALYST;
SHOW GRANTS TO ROLE SIDEFLIX_RUNNER;

-- Real consumption and storage: keep periods and raw results, not an invented zero.
SELECT START_TIME,END_TIME,WAREHOUSE_NAME,CREDITS_USED_COMPUTE,
 CREDITS_USED_CLOUD_SERVICES,CREDITS_USED
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME='SIDEFLIX_WH' AND START_TIME>=DATEADD(day,-7,CURRENT_TIMESTAMP())
ORDER BY START_TIME;
SELECT TABLE_CATALOG,SUM(ACTIVE_BYTES),SUM(TIME_TRAVEL_BYTES),SUM(FAILSAFE_BYTES)
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLE_STORAGE_METRICS
WHERE TABLE_CATALOG='SIDEFLIX' GROUP BY 1;
